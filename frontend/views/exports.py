import json

import pandas as pd
import streamlit as st

import api_client as api
from components.cards import metric_cards
from components.theme import C, page_header
from views.common import api_error_box, summary


def _dl(path, params=()):
    try:
        return api.download(path, params)
    except api.APIError as e:
        st.error(str(e))
        return None, {}


def render():
    page_header("Reports & Exports", "Every file is generated by the backend from the current results and editor decisions.")
    api_error_box()
    s = summary()
    if not s or not s["ranked"]:
        st.info("Run the pipeline first.")
        return
    rv = s["review"]
    c1, c2, c3 = st.columns(3)
    with c1:
        with st.container(border=True):
            st.markdown("**1 · Approved promos only**")
            fmt = st.radio("Format", ["csv", "json"], horizontal=True, label_visibility="collapsed")
            data, hdr = _dl("/api/reports/approved", (("fmt", fmt),))
            n = int(hdr.get("x-row-count", hdr.get("X-Row-Count", 0)) or 0)
            st.caption(f"{n} approved promo(s)" if n else "Nothing approved yet: the file will have 0 rows.")
            if data is not None:
                st.download_button(f"⬇ approved_promos.{fmt}", data, f"approved_promos.{fmt}", type="primary",
                                   use_container_width=True)
    with c2:
        with st.container(border=True):
            st.markdown("**2 · All promos + decisions (CSV)**")
            data, hdr = _dl("/api/reports/all-decisions")
            st.caption(f"{rv['total']} ranked promos · {rv['reviewed']} reviewed")
            if data is not None:
                st.download_button("⬇ all_promos_decisions.csv", data, "all_promos_decisions.csv", type="primary",
                                   use_container_width=True)
    with c3:
        with st.container(border=True):
            st.markdown("**3 · Full report (ranked.md)**")
            data, _ = _dl("/api/reports/full")
            st.caption("Rankings, segments, scores, validation, audiences, secrets and decisions.")
            if data is not None:
                st.download_button("⬇ ranked.md", data, "ranked.md", type="primary", use_container_width=True)

    st.markdown("#### More downloads")
    cols = st.columns(4)
    for col, name in zip(cols, ["ranked_promos.json", "evaluation_results.csv", "agent_execution_trace.json",
                                "agent_run_summary.json"]):
        data, _ = _dl(f"/api/reports/file/{name}")
        if data is not None:
            col.download_button(name, data, name, use_container_width=True)

    st.markdown("#### Evaluation")
    ev = api.safe_get("/api/reports/evaluation")
    if ev:
        metric_cards([("Hook within 3s", f"{ev['hook_within_3s_rate'] * 100:.0f}%", "of ranked promos", C["success"]),
                      ("Episode coverage", ev["episode_coverage"], "episodes with a valid promo", C["secondary"]),
                      ("Mean duration", f"{ev['mean_duration_s']}s", "target 20–60s", C["cyan"]),
                      ("Needs human review", str(ev["needs_human_review"]), "quality reviewer escalations", C["warning"]),
                      ("LLM-judged", str(ev["llm_judged"]), ev["provider"], C["primary"])])
        ref = ev.get("reference", {})
        if ref.get("available"):
            st.markdown(f"**Reference check:** {ref['recall_any_rank'] * 100:.0f}% of {len(ref['moments'])} must-have moments appear "
                        f"in the ranking, {ref['recall_top_k'] * 100:.0f}% in the top {ref['top_k']}. "
                        "(Small, AI-drafted reference set: an editor should confirm it.)")
            st.dataframe(pd.DataFrame([{"Moment": m["id"], "Episode": m["episode"], "What": m["why"],
                                        "Best rank": m.get("best_rank") or "not found",
                                        f"In top {ref['top_k']}": "✅" if m["hit_top_k"] else "—"} for m in ref["moments"]]),
                         hide_index=True, use_container_width=True)
        with st.expander("Raw evaluation JSON"):
            st.code(json.dumps({k: v for k, v in ev.items() if k != "reference"}, indent=1), language="json")
